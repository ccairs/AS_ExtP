// solverMaskPolicy.h —— 结算器「时变掩码」的逐会话更新策略（纯逻辑，可单测）
//
// 背景：
// 打关键帧/表达式的槽位会被判为「时变」，其值退出参数指纹（逐帧读当帧值）——这是
// 关键帧驱动结算的基础。但掩码载体是 sticky「只置位不清位」：删光关键帧、切回静态值
// 之后，槽位仍被当作时变 → 指纹里该槽的标记字节恒为 0x02、值始终不进指纹 →
// **改静态值不重解**（用户拖滑块画面不动）。
//
// 修复：把「本会话判定为静态」也作为一等结果传出来，允许清位：
//   · 本会话判定为时变（含关键帧/表达式） → 置位；
//   · 本会话**判定成功且为静态** → 清位（标记字节 0x02→0x01 → 谱系键变化 → 重解一次；
//     此后该槽是静态槽，值进指纹，改值即重解）；
//   · 判定失败/不可得（AEGP 间歇失败等） → 沿用上次（sticky），防指纹在「含值/不含值」
//     之间振荡导致谱系键逐帧漂移（这是 sticky 的原始意图，保留）。
//
// 两个输入掩码由调用方保证按位互斥（同一槽位要么「任一分量时变」要么「全部分量判定
// 成功且均静态」；判定失败的分量两个掩码都不置位）。公式对重叠输入也安全。
#pragma once
#include <cstdint>

namespace host {

inline uint32_t updateVaryingMaskSticky(uint32_t prev, uint32_t varyingNow, uint32_t staticConfirmed) {
    return (prev | varyingNow) & ~staticConfirmed;
}

} // namespace host
